"""
models/validation_models.py — Validation-layer data structures.

Defines ValidationIssue and ValidationReport produced by the
validation step of the extraction pipeline.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import List


@dataclass
class ValidationIssue:
    """An issue found during statement validation.

    Attributes:
        issue_type:  The type of issue (e.g., 'date_parse_failure',
                     'missing_columns').
        severity:    The severity of the issue ('WARNING' or 'ERROR').
        description: Human-readable explanation of the issue.
    """

    issue_type: str
    severity: str
    description: str


@dataclass
class ValidationReport:
    """Report generated by the validation engine.

    Attributes:
        passed:     True if no ERROR severity issues are present.
        confidence: An overall confidence score [0.0, 1.0].
        issues:     List of validation issues detected.
    """

    passed: bool = True
    confidence: float = 1.0
    issues: List[ValidationIssue] = field(default_factory=list)